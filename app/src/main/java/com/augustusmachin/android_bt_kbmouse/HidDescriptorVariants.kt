package com.augustusmachin.android_bt_kbmouse

/** Helpers to build simplified vs full HID report descriptor variants for Windows experiments. */
object HidDescriptorVariants {
    // Full descriptor (keyboard + mouse + media + hwheel placeholder simplified)
    val FULL = byteArrayOf( /* full descriptor start */
        // Keyboard (mods + keys same as production) truncated example
        0x05,0x01,0x09,0x06,0xA1.toByte(),0x01,
        0x05,0x07,0x19.toByte(),0xE0.toByte(),0x29.toByte(),0xE7.toByte(),0x15,0x00,0x25,0x01,0x75,0x01,0x95.toByte(),0x08,0x81.toByte(),0x02,
        0x95.toByte(),0x01,0x75,0x08,0x81.toByte(),0x01,
        0x95.toByte(),0x06,0x75,0x08,0x15,0x00,0x25,0x65,0x05,0x07,0x19.toByte(),0x00,0x29.toByte(),0x65,0x81.toByte(),0x00,
        0xC0.toByte(),
        // Mouse with buttons + X/Y
        0x05,0x01,0x09,0x02,0xA1.toByte(),0x01,0x09,0x01,0xA1.toByte(),0x00,
        0x05,0x09,0x19.toByte(),0x01,0x29.toByte(),0x03,0x15,0x00,0x25,0x01,0x75,0x01,0x95.toByte(),0x03,0x81.toByte(),0x02,
        0x75,0x05,0x95.toByte(),0x01,0x81.toByte(),0x01,
        0x05,0x01,0x09,0x30,0x09,0x31,0x15,0x81.toByte(),0x25,0x7F,0x75,0x08,0x95.toByte(),0x02,0x81.toByte(),0x06,
        // Add Consumer Control Play/Pause to make full variant longer than simple
        0x05,0x0C,0x09,0xCD.toByte(),0x15,0x00,0x25,0x01,0x75,0x01,0x95.toByte(),0x01,0x81.toByte(),0x02,
        0xC0.toByte(),0xC0.toByte()
    )
    // Simplified descriptor: only keyboard modifiers + 6 keys, and basic mouse (no scroll wheels, no media)
    val SIMPLE = byteArrayOf(
        0x05,0x01,0x09,0x06,0xA1.toByte(),0x01, // keyboard app
        0x05,0x07,0x19.toByte(),0xE0.toByte(),0x29.toByte(),0xE7.toByte(),0x15,0x00,0x25,0x01,0x75,0x01,0x95.toByte(),0x08,0x81.toByte(),0x02,
        0x95.toByte(),0x01,0x75,0x08,0x81.toByte(),0x01, // reserved
        0x95.toByte(),0x06,0x75,0x08,0x15,0x00,0x25,0x65,0x05,0x07,0x19.toByte(),0x00,0x29.toByte(),0x65,0x81.toByte(),0x00,
        0xC0.toByte(),
        0x05,0x01,0x09,0x02,0xA1.toByte(),0x01,0x09,0x01,0xA1.toByte(),0x00,
        0x05,0x09,0x19.toByte(),0x01,0x29.toByte(),0x03,0x15,0x00,0x25,0x01,0x75,0x01,0x95.toByte(),0x03,0x81.toByte(),0x02,
        0x75,0x05,0x95.toByte(),0x01,0x81.toByte(),0x01,
        0x05,0x01,0x09,0x30,0x09,0x31,0x15,0x81.toByte(),0x25,0x7F,0x75,0x08,0x95.toByte(),0x02,0x81.toByte(),0x06,
        0xC0.toByte(),0xC0.toByte()
    )

    fun select(simplified: Boolean): ByteArray = if (simplified) SIMPLE else FULL
}
